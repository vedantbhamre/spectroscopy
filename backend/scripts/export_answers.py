"""Export the assistant's stored answers as readable Markdown for the jury: answers/<ID>.md and answers/README.md.

    python -m scripts.export_answers

Input: frontend/outputs/<ID>.json, written by `python -m scripts.run_batch` (the live pipeline). This script only
formats them; it never edits or writes answer content.
"""

import json
from pathlib import Path

from app.config import BACKEND_DIR

ROOT = BACKEND_DIR.parent
OUTPUTS = ROOT / "frontend" / "outputs"
ANSWERS = ROOT / "answers"
SCENARIOS = json.loads((BACKEND_DIR / "data" / "scenarios.json").read_text())

SOURCE_NAMES = {
    "S01": "AFS Multispectral Laboratory guide", "S02": "AFS Process Control slides", "S03": "LED kidney tissue study (2017)",
    "S04": "Combined MIR + fluorescence study (2021)", "S05": "AFS flyer", "S06": "AFS laboratory web page",
}
STATUS = {"provisional": "Provisional feasibility assessment", "insufficient": "Insufficient information",
          "out_of_scope": "Beyond what the sources support"}
CHECK = {"pass": "pass", "flag": "flag", "fail": "FAIL"}


def cite(c: dict) -> str:
    page = c["page"] if str(c["page"]).startswith("Table") else f"p.{c['page']}"
    return f"{c['source']} {page}"


def cites(cs: list[dict]) -> str:
    return f" [{'; '.join(dict.fromkeys(cite(c) for c in cs))}]" if cs else ""


def bullets(items: list[str]) -> list[str]:
    return [f"- {x}" for x in items] or ["- none"]


def render(s: dict, data: dict) -> str:
    r = data["report"]
    model = next((t.get("detail", "") for t in data.get("trace", []) if t.get("step") == "Compose the assessment"), "")
    L = [f"# {s['id']}: {s['title']}", "",
         f"Generated by the live SpectraSense pipeline ({model or 'model not recorded'}), {r.get('generatedAt', '')}. "
         "Exported unchanged from `frontend/outputs/" + s["id"] + ".json`.", "",
         "## Customer enquiry", "", f"> {s['enquiry']}", "",
         f"**Decision status:** {STATUS.get(r['decisionStatus'], r['decisionStatus'])}", ""]
    if r.get("answer"):
        L += ["## Answer", "", r["answer"]["text"] + cites(r["answer"].get("citations", [])), ""]
        if r["answer"].get("sayInstead"):
            L += [f"**What the customer can say instead:** {r['answer']['sayInstead']}", ""]
    if r.get("premiseChecks"):
        L += ["## Premise checks", ""]
        L += [f"- **{CHECK[c['status']]}**: {c['label']}. {c['detail']}{cites(c.get('citations', []))}" for c in r["premiseChecks"]]
        L += [""]
    L += ["## Requirements", "", "**Stated by the customer**", *bullets(r["requirements"]["stated"]), "",
          "**Unknown, not assumed**", *bullets(r["requirements"]["unknowns"]), ""]
    open_q = [q for q in r.get("questions", []) if q.get("status", "open") == "open"]
    if open_q:
        L += ["## Clarification questions", "", *[f"{i}. {q['text']}" for i, q in enumerate(open_q, 1)], ""]
    L += ["## Recommendation", ""]
    for rec in r["recommendations"] or []:
        L += [f"- **{rec['method']}** ({rec['role'].replace('_', ' ')}): {rec['reason']}{cites(rec.get('citations', []))}"]
        L += [f"  - Limitation: {x}" for x in rec.get("limitations") or []]
    if not r["recommendations"]:
        L += ["- No method is recommended yet; see the decision status and the questions."]
    c = r["concept"]
    L += ["", "## Measurement concept", "", c["summary"] + cites(c.get("citations", [])), ""]
    L += [f"- **{k}:** {c[f]}" for k, f in (("Analyzer", "analyzer"), ("Fibre link", "fiberLink"), ("Probe", "probe"), ("Process point", "location")) if c.get(f)]
    L += ["", "## Spectral range", "", r["spectralRange"]["summary"] + cites(r["spectralRange"].get("citations", [])), "",
          "## Risks and uncertainty", "", *bullets(r["risks"]), "",
          "## First feasibility experiment", "", *[f"{i}. {x}" for i, x in enumerate(r["feasibility"]["steps"], 1)], "",
          f"**Decision basis:** {r['feasibility']['decisionBasis']}", ""]
    if r.get("assumptions"):
        L += ["## Assumptions", "", *bullets(r["assumptions"]), ""]
    if r.get("pointsToConfirm"):
        L += ["## Points to confirm", "", *bullets(r["pointsToConfirm"]), ""]
    L += ["## Sources", ""]
    for src in r.get("sources", []):
        name = SOURCE_NAMES.get(src["source"], src["source"])
        check = f" ({src['check']})" if src.get("check") else ""
        L += [f"- **{cite(src)}**, {name}{check}" + (f": “{src['quote']}”" if src.get("quote") else "")]
    return "\n".join(L).rstrip() + "\n"


def main() -> None:
    ANSWERS.mkdir(exist_ok=True)
    rows = {"evaluation": [], "development": []}
    for s in SCENARIOS:
        path = OUTPUTS / f"{s['id']}.json"
        if not path.exists():
            continue
        data = json.loads(path.read_text())
        (ANSWERS / f"{s['id']}.md").write_text(render(s, data))
        r = data["report"]
        first = (r.get("answer") or {}).get("text", "").split(". ")[0].rstrip(".")
        rows[s["set"]].append(f"| [{s['id']}]({s['id']}.md) | {s['title']} | {STATUS.get(r['decisionStatus'], r['decisionStatus'])} | {first}. |")
    head = ["| ID | Enquiry | Status | Answer (first sentence) |", "|---|---|---|---|"]
    index = ["# Assistant answers", "",
             "Generated by the live SpectraSense pipeline (`python -m scripts.run_batch`) and exported unchanged to Markdown",
             "(`python -m scripts.export_answers`). Each file holds the enquiry, the answer, the premise checks, the recommendation",
             "with its page citations, the measurement concept, the feasibility plan and every quoted source.", "",
             "## Final evaluation scenarios (H01–H06)", "", *head, *rows["evaluation"], "",
             "## Development scenarios (D01–D08)", "", *head, *rows["development"], ""]
    (ANSWERS / "README.md").write_text("\n".join(index))
    print(f"wrote {sum(map(len, rows.values()))} answers to {ANSWERS.relative_to(ROOT)}/")


if __name__ == "__main__":
    main()
